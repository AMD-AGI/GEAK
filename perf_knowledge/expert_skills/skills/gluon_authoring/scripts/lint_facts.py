#!/usr/bin/env python3
"""lint_facts.py - validate facts.jsonl and (re)generate INDEX.md. stdlib only.

  lint_facts.py [--root <skill dir>] [--pack]       lint; exit 1 on any finding
  lint_facts.py --write-index [--root <skill dir>]  regenerate INDEX.md from facts.jsonl

Checks: JSON per line; required fields and types (optional `method`: one line, how the card was
verified; required for evidence gpu-measured); no provenance fields (src, merged_from stay in the
build source); unique ids of form <group>.<slug> with a known group; kind and evidence vocabularies;
see[] ids resolve; check non-empty and not cwd-relative (bare scripts/ or data/); overrides[] only
in the GEAK pack (--pack) and only naming existing GEAK knowledge files; $SKILL/scripts/<x> and $KT/<x>
named in claim/check exist; KT_*/GEAK_* env names in claim/check/keys are read by this tree's
scripts; leak patterns (benchmark task names,
run records, timings, dates, provenance); absolute/prescriptive words outside kind error|trap;
INDEX.md equal to its generated form.
"""
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GROUPS = ("api layout mfma lowp mem async lds sync pipe wpipe asm compiler attrs isa occ hw sku prof "
          "tool port rt error").split()
KINDS = {"fact", "error", "api", "isa", "hw", "tool", "trap"}
FIELDS = {"id": str, "kind": str, "claim": str, "scope": dict, "evidence": str, "signal": str,
          "check": str, "keys": list, "overrides": list, "see": list}
OPTIONAL = {"method": str}
PROVENANCE = ("src", "merged_from", "pack")
EVIDENCE = re.compile(r"^(compile-checked|gpu-measured|unverified|source:\S.*|doc:\S.*)$")
ID = re.compile(r"^([a-z]+)\.[a-z0-9][a-z0-9-]*$")
# Leak patterns: benchmark task names/families, run records, provenance, timings, dates.
LEAKS = [
    r"\b\d\d_(gemm|moe|sparse|pa_|chunk|mha|kda|fp8|unified|mxfp8)", r"gemm_a\d+w\d+", r"\ba\d+w\d+\b",
    r"\bafp4wfp4\b", r"blockscale", r"mxfp8_block32", r"sparse_mla", r"\bMLA\b", r"\bKDA\b",
    r"chunk_kda", r"kda_decode", r"\bDSA\b", r"mqa_logits", r"pa_mqa", r"mha_prefill", r"mha_fp8",
    r"unified_attention", r"triton ports?\b", r"in the runs?\b", r"runs recorded", r"recorded runs?",
    r"measured on that", r"\bA/B\b", r"\bround[ -]?\d", r"\bagent [A-E]\b", r"\bR[1-9]\b",
    r"one MI3\d\dX node", r"\b20\d\d-\d\d(-\d\d)?\b", r"\bchampion", r"\bwinn(ing|er)\b",
    r"\bspeed-?ups?\b", r"\b\d+(\.\d+)?\s?x (faster|slower)\b", r"\b\d+(\.\d+)?\s?(us|µs|ms)\b",
    r"\bour (runs?|tasks?|kernels?|node)\b", r"\bthe task\b", r"\btask \d",
    r"skill-v1#", r"\bworkloads?/", r"moe-lowprec", r"linear-attention", r"attention-lowprec",
    r"flash-attention-structural", r"had to retract", r"recorded (results|wins)", r"\bscratch_\w+",
    r"\bval/", r"\bgpu_[AB]\b", r"\bformer skill\b",
]
LEAK_RX = [re.compile(p, re.I if p.islower() else 0) for p in LEAKS]
SCRIPT_RX = re.compile(r"(\$SKILL/scripts/|\$KT/)([A-Za-z0-9_.-]+\.(?:py|sh))")
CWD_RX = re.compile(r"(?<![\w$/.-])(scripts|data)/[A-Za-z0-9_.*-]+")
ROOT_SCRIPT_RX = re.compile(r"(?<![\w$/.-])((?:kernel_workflow/|e2e_workflow/)?scripts/[A-Za-z0-9_.-]+\.(?:py|sh))")
ENV_RX = re.compile(r"\b(?:KT_[A-Z0-9_]+|GEAK_[A-Z0-9_]+|GLUON_SKILL_DATA_DIR)\b")


def env_names(dirs):
    names = set()
    for d in dirs:
        for base, sub, files in os.walk(d):
            sub[:] = [x for x in sub if x not in ("__pycache__", "tests")]
            for f in files:
                if f.endswith((".py", ".sh", ".js")):
                    try:
                        with open(os.path.join(base, f), encoding="utf-8", errors="ignore") as fh:
                            names |= set(ENV_RX.findall(fh.read()))
                    except OSError:
                        pass
    return names
ABSOLUTE = re.compile(r"\b(always|never|must|should|mandatory|recommended|best practice|top lever)\b",
                      re.I)


def load(path):
    cards, errs = [], []
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            if not line.strip():
                continue
            try:
                cards.append(json.loads(line))
            except ValueError as exc:
                errs.append(f"line {n}: bad JSON: {exc}")
    return cards, errs


def gen_index(cards):
    out = ["# INDEX - generated by scripts/lint_facts.py --write-index from facts.jsonl; do not edit",
           "",
           "Query with `python3 scripts/q.py \"<words or pasted error>\"`; `--id <id>` prints a card.",
           "Line format: `id` [kind, evidence] keys. `U` = evidence unverified.", ""]
    groups = {}
    for c in cards:
        groups.setdefault(c["id"].split(".")[0], []).append(c)
    for g in sorted(groups):
        out.append(f"## {g} ({len(groups[g])})")
        for c in sorted(groups[g], key=lambda c: c["id"]):
            ev = c["evidence"].split(":")[0]
            ev = "U" if ev == "unverified" else ev
            keys = "; ".join(k.replace("|", "\\|").replace("\n", " ") for k in c.get("keys", [])[:8])
            out.append(f"- `{c['id']}` [{c['kind']}, {ev}] {keys}")
        out.append("")
    out.append("## error string -> card")
    out.append("")
    out.append("| error / message (verbatim key) | card |")
    out.append("| --- | --- |")
    rows = []
    for c in cards:
        if c["kind"] not in ("error", "trap"):
            continue
        for k in c.get("keys", []):
            if len(k) >= 12 and " " in k.strip():
                rows.append((k.strip().replace("|", "\\|").replace("\n", " "), c["id"]))
    for k, i in sorted(set(rows), key=lambda r: (r[0].lower(), r[0], r[1])):
        out.append(f"| `{k}` | `{i}` |")
    out.append("")
    return "\n".join(out)


def lint(cards, pack, root=None):
    scripts = os.path.join(root, "scripts") if root else None
    geak = os.path.normpath(os.path.join(root, "..", "..", "..", "..")) if (root and pack) else None
    kt = os.path.join(geak, "kernel_workflow", "scripts", "kernel_tools") if geak else None
    root = scripts
    errs = []
    if scripts:
        dirs = [scripts] + ([kt, os.path.join(geak, "kernel_workflow", "scripts"), os.path.join(geak, "scripts"),
                             os.path.join(geak, "e2e_workflow", "scripts")] if geak else [])
        known_env = env_names([d for d in dirs if os.path.isdir(d)])
    else:
        known_env = None
    ids = [c.get("id") for c in cards]
    seen = set()
    for i in ids:
        if i in seen:
            errs.append(f"duplicate id {i}")
        seen.add(i)
    for c in cards:
        cid = c.get("id", "?")
        for f, t in FIELDS.items():
            if f not in c:
                errs.append(f"{cid}: missing field {f}")
            elif not isinstance(c[f], t):
                errs.append(f"{cid}: field {f} is not {t.__name__}")
        prov = [f for f in PROVENANCE if f in c]
        if prov:
            errs.append(f"{cid}: provenance field(s) {prov} rendered into the tree")
        extra = set(c) - set(FIELDS) - set(OPTIONAL) - set(PROVENANCE)
        if extra:
            errs.append(f"{cid}: unknown fields {sorted(extra)}")
        for f, t in OPTIONAL.items():
            if f in c and not isinstance(c[f], t):
                errs.append(f"{cid}: field {f} is not {t.__name__}")
        meth = c.get("method")
        if isinstance(meth, str) and (not meth.strip() or "\n" in meth):
            errs.append(f"{cid}: method is empty or not one line")
        if c.get("evidence") == "gpu-measured" and not meth:
            errs.append(f"{cid}: evidence gpu-measured without a method")
        m = ID.match(cid or "")
        if not m:
            errs.append(f"{cid}: id not <group>.<slug>")
        elif m.group(1) not in GROUPS:
            errs.append(f"{cid}: unknown group {m.group(1)}")
        if c.get("kind") not in KINDS:
            errs.append(f"{cid}: kind {c.get('kind')!r} not in {sorted(KINDS)}")
        if not EVIDENCE.match(str(c.get("evidence", ""))):
            errs.append(f"{cid}: evidence {c.get('evidence')!r} not in vocabulary")
        sc = c.get("scope", {})
        if isinstance(sc, dict):
            for k, t in (("arch", list), ("triton", str), ("dtype", list), ("regime", str)):
                if not isinstance(sc.get(k), t):
                    errs.append(f"{cid}: scope.{k} missing or not {t.__name__}")
        if not str(c.get("check", "")).strip():
            errs.append(f"{cid}: empty check")
        for mm in CWD_RX.finditer(str(c.get("check", ""))):
            if not (pack and mm.group(0).startswith("scripts/") and geak and
                    os.path.exists(os.path.join(geak, mm.group(0)))):
                errs.append(f"{cid}: check names cwd-relative {mm.group(0)!r} (use $SKILL/... or a GEAK-root path)")
        if geak:
            for mm in ROOT_SCRIPT_RX.finditer(" ".join(str(c.get(f, "")) for f in ("claim", "check"))):
                if not os.path.exists(os.path.join(geak, mm.group(1))):
                    errs.append(f"{cid}: names {mm.group(1)}, which this GEAK checkout does not ship")
        if known_env is not None:
            for f in ("claim", "check", "signal", "keys"):
                v = c.get(f, "")
                for n in ENV_RX.findall(" ".join(v) if isinstance(v, list) else str(v)):
                    if n not in known_env:
                        errs.append(f"{cid}: {f} names env {n}, which no script in this tree reads")
        if not str(c.get("claim", "")).strip():
            errs.append(f"{cid}: empty claim")
        for s in c.get("see", []):
            if s not in seen:
                errs.append(f"{cid}: see[] {s} does not resolve")
        ov = c.get("overrides", [])
        if ov and not pack:
            errs.append(f"{cid}: overrides[] present outside the GEAK pack")
        for o in ov:
            if not str(o).startswith(("perf_knowledge/", "kernel_workflow/knowledge/")):
                errs.append(f"{cid}: overrides entry {o!r} is not a GEAK knowledge path")
            elif geak and not os.path.exists(os.path.join(geak, o)):
                errs.append(f"{cid}: overrides entry {o} does not exist")
        for m in SCRIPT_RX.finditer(" ".join(str(c.get(f, "")) for f in ("claim", "check"))):
            base = root if m.group(1) == "$SKILL/scripts/" else kt
            if base and not os.path.exists(os.path.join(base, m.group(2))):
                errs.append(f"{cid}: names {m.group(1)}{m.group(2)}, which does not exist")
        text = " ".join(str(c.get(f, "")) for f in ("claim", "signal", "check", "method")) + " " + \
            " ".join(map(str, c.get("keys", [])))
        for rx in LEAK_RX:
            mm = rx.search(text)
            if mm:
                errs.append(f"{cid}: leak pattern {rx.pattern!r} matched {mm.group(0)!r}")
        if c.get("kind") not in ("error", "trap"):
            mm = ABSOLUTE.search(c.get("claim", ""))
            if mm:
                errs.append(f"{cid}: absolute word {mm.group(0)!r} in a kind:{c.get('kind')} claim")
    return errs


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter,
                                 epilog=__doc__.split("\n\n", 1)[1])
    ap.add_argument("--root", default=os.path.dirname(HERE), help="skill dir holding facts.jsonl")
    ap.add_argument("--pack", action="store_true", help="GEAK pack mode (overrides[] allowed)")
    ap.add_argument("--write-index", action="store_true", help="regenerate INDEX.md and exit")
    a = ap.parse_args(argv)
    facts = os.path.join(a.root, "facts.jsonl")
    index = os.path.join(a.root, "INDEX.md")
    cards, errs = load(facts)
    if a.write_index:
        if errs:
            print("\n".join(errs), file=sys.stderr)
            return 1
        with open(index, "w", encoding="utf-8") as f:
            f.write(gen_index(cards))
        print(f"wrote {index} ({len(cards)} cards)")
        return 0
    errs += lint(cards, a.pack, a.root)
    try:
        with open(index, encoding="utf-8") as f:
            if f.read() != gen_index(cards):
                errs.append("INDEX.md is stale: run lint_facts.py --write-index")
    except OSError:
        errs.append("INDEX.md missing: run lint_facts.py --write-index")
    for e in errs:
        print("LINT " + e)
    print(f"lint_facts: {len(cards)} cards, {len(errs)} finding(s)")
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
