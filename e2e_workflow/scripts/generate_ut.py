#!/usr/bin/env python3
"""Scaffold, check and freeze a kernel UT task around the agent's cases.py and meta.json.

    python3 generate_ut.py all    TASK      # vendor -> check -> freeze, rerunning what changed
    python3 generate_ut.py vendor TASK      # runtime files + the fixed unittest.py + baseline_overlay/
    python3 generate_ut.py check  TASK      # CPU-only: hooks, metadata, coverage, GPU-count declaration
    python3 generate_ut.py freeze TASK      # run/ut_contract.json: the test contract hash

    --ranking KERNEL_RANKING_JSON           # the extraction's kernel ranking (A35): its absolute path is
                                            # written into meta.kernel_extraction.ranking_json first

The agent writes cases.py and meta.json (task-authoring.md); everything else is generated:

  vendor  copies harness_lib.py, leg_runner.py, overlay_setup.py and ut_runner.py from this directory
          unchanged, writes a unittest.py whose first line is the generated marker and which only calls
          ut_runner.py, creates an empty baseline_overlay/ when there is none, and registers the runtime
          files in meta.kernel_extraction.source_delivery_files (so the source snapshot binds them). A
          hand-written unittest.py (no marker) is never overwritten unless --force is given.
  check   parses cases.py without importing it (a cases.py construct can never crash the check) and
          verifies: the hooks the declared capabilities need (call, timing_cases, random_shapes,
          eager_cases; replay for a graph-deployed phase; sequence_cases for a stateful task; setup is
          optional for multi-rank), the required metadata (meta.workload is optional: without it the
          UT times unweighted), the graph capture of every graph-deployed phase and the `m` of its timed
          cases (A18), the stateful tiers of a stateful task, the declared GPU count against
          run/requested_kernel.json, and the case manifest's coverage: every bucket of the declared
          dimensions has both a timing and a correctness case (a correctness-only boundary case,
          "boundary": true, forms no bucket: A40), every positive-mass observed case is
          timed (ISSUE-006, generalised from width x context to any declared dimension), and every
          phase the kernel has calls in -- its row of the extraction's kernel ranking
          (meta.kernel_extraction.ranking_json, required for an agentx_trace_replay workload),
          meta.workload.cases, meta.workload.uncovered -- is served and has timing and correctness
          cases (A35); meta.workload.uncovered only holds the rest of a covered phase. Every
          kernel_src/ source file is either copied source (meta.kernel_extraction.source_origins) or a
          binding file written for the task (meta.kernel_extraction.binding_files) (A16 C').
  freeze  hashes the test contract (ut_runner.contract_file_list: unittest.py, cases.py, meta.json
          with its tolerance, runtime files, baseline_overlay/, control definitions, reference data)
          into run/ut_contract.json. kernel_src/ is NOT in it: the existing source snapshot covers the
          candidate source, so editing only kernel_src/ re-verifies the candidate, while editing the
          test invalidates every earlier verdict. The contract also records the origins of the copied
          source and the declared binding files with their sha256 (what verify_ut's A/A rule reads).

Every step records the files it read and wrote with their sha256 in run/ut_generate.json. `all` reruns a
step whose recorded inputs or outputs no longer match the disk, and then every later step in the same
invocation (ISSUE-019 on top of UT-001); running one step alone drops the records of the later steps.
"""
