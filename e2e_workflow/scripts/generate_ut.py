def kernel_src_sources(task):
    """kernel_src/ source files as the source snapshot lists them (task-relative paths)."""
    out = []
    root = os.path.join(task, "kernel_src")
    for dirpath, dirs, files in os.walk(root):
        dirs[:] = sorted(d for d in dirs if d != "__pycache__")
        for f in sorted(files):
            if ut_runner.SOURCE_EXT.search(f):
                out.append(os.path.relpath(os.path.join(dirpath, f), task))
    return out


def check_kernel_src_classes(task, meta, p):
    """A16 C': every kernel_src/ source file is EITHER copied source with the installed file it was copied
    from (meta.kernel_extraction.source_origins) OR a binding file written for the task
    (meta.kernel_extraction.binding_files: bindings, wrappers, build glue). verify_ut's A/A runs through the
    candidate binding only when the copied source is byte-identical to its origins."""
    ke = meta.get("kernel_extraction") if isinstance(meta.get("kernel_extraction"), dict) else {}
    origins = ke.get("source_origins") or {}
    if not isinstance(origins, dict):
        p.add("meta.kernel_extraction.source_origins must map kernel_src/ paths to the installed files they "
              "were copied from")
        origins = {}
    raw = ke.get("binding_files")
    if raw is not None and (not isinstance(raw, list) or not all(isinstance(x, str) for x in raw)):
        p.add("meta.kernel_extraction.binding_files must be a list of kernel_src/ paths")
        raw = []
    bindings = [os.path.normpath(x) for x in raw or []]
    for b in bindings:
        if b.split(os.sep)[0] != "kernel_src":
            p.add(f"meta.kernel_extraction.binding_files: {b} is not under kernel_src/")
        elif not os.path.isfile(os.path.join(task, b)):
            p.add(f"meta.kernel_extraction.binding_files: {b} does not exist")
        if b in {os.path.normpath(k) for k in origins}:
            p.add(f"{b} is listed both as copied source (source_origins) and as a binding file: it is one or "
                  "the other")
    known = {os.path.normpath(k) for k in origins} | set(bindings)
    loose = [f for f in kernel_src_sources(task) if os.path.normpath(f) not in known]
    if loose:
        p.add("kernel_src/ files are either copied source (meta.kernel_extraction.source_origins: the installed "
              "file each was copied from) or binding files written for the task "
              "(meta.kernel_extraction.binding_files); unclassified: "
              + ", ".join(loose[:12]) + (" ..." if len(loose) > 12 else ""))


def check_manifest(meta, p):
    """ISSUE-006 generalised: every bucket of the declared dimensions has a timing and a correctness case. A
    boundary case (A40: "boundary": true, correctness only, every dimension filled in) forms no bucket: it needs
    no timing case and no observed row, and the UT still has to run and compare it (ut_runner.manifest_problems)."""
    man = meta.get("case_manifest")
    if not isinstance(man, dict) or not isinstance(man.get("cases"), list) or not man["cases"]:
        p.add("meta.case_manifest {dims: [...], cases: [{sig, <dims>, roles: [timing|correctness]}]} is required")
        return
    dims = man.get("dims") or ["regime"]
    if not isinstance(dims, list) or not all(isinstance(d, str) and d for d in dims):
        p.add("meta.case_manifest.dims must be a list of field names")
        return
    buckets = {}
    sigs = set()
    for c in man["cases"]:
        if not isinstance(c, dict) or not c.get("sig"):
            p.add(f"case_manifest case without sig: {c!r}")
            continue
        if c["sig"] in sigs:
            p.add(f"case_manifest has duplicate sig {c['sig']}")
        sigs.add(c["sig"])
        roles = c.get("roles")
        if not isinstance(roles, list) or not roles or any(r not in ("timing", "correctness") for r in roles):
            p.add(f"case_manifest case {c['sig']}: roles must be a non-empty subset of [timing, correctness]")
            continue
        boundary = c.get("boundary", False)
        if not isinstance(boundary, bool):
            p.add(f"case_manifest case {c['sig']}: boundary must be true or false")
            boundary = False
        elif boundary and "timing" in roles:
            p.add(f"case_manifest case {c['sig']}: a boundary case (boundary: true) is a correctness case only; "
                  "time the observed workload's cases instead (task-authoring.md, \"Seeded inputs by default\")")
            boundary = False
        missing = [d for d in dims if d not in c]
        if missing:
            p.add(f"case_manifest case {c['sig']} lacks dimension(s) {missing}")
            continue
        if boundary:
            continue                      # A40: an observed-range end checked for correctness, not a bucket
        key = tuple(json.dumps(c[d], sort_keys=True) for d in dims)
        buckets.setdefault(key, set()).update(roles)
    for key, roles in sorted(buckets.items()):
        label = ", ".join(f"{d}={json.loads(v)}" for d, v in zip(dims, key))
        for need in ("timing", "correctness"):
            if need not in roles:
                p.add(f"coverage bucket [{label}] has no {need} case")
    timed = {c.get("sig") for c in man["cases"] if isinstance(c, dict) and "timing" in (c.get("roles") or [])}
    wl = (meta.get("workload") or {}).get("cases") or []
    served = {str(r).strip().lower() for r in (meta.get("served_regimes") or
                                                (meta.get("workload") or {}).get("served_regimes") or [])}
    for c in wl:
        try:
            mass = float(c.get("effective_calls"))
        except (TypeError, ValueError):
            continue
        reg = str(c.get("regime") or "").strip().lower()
        if mass > 0 and (not served or reg in served) and c.get("sig") not in timed:
            p.add(f"observed case {c.get('sig')} has positive call mass but no timing case in the manifest")


