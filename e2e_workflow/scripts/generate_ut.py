def _ws(s):
    """A kernel name with its whitespace runs collapsed (ranking rows are matched on it)."""
    return re.sub(r"\s+", " ", s).strip() if isinstance(s, str) else None


def _positive(x):
    if isinstance(x, bool):
        return False
    try:
        return float(x) > 0
    except (TypeError, ValueError):
        return False


def _names(x):
    """The non-empty strings of a name field (a string or a list of strings)."""
    vals = x if isinstance(x, list) else [x]
    return [v for v in vals if isinstance(v, str) and v.strip()]


def ranking_path(task, meta):
    """meta.kernel_extraction.ranking_json (absolute, or relative to the task dir), or None."""
    ke = meta.get("kernel_extraction") if isinstance(meta.get("kernel_extraction"), dict) else {}
    p = ke.get("ranking_json")
    if not isinstance(p, str) or not p.strip():
        return None
    p = os.path.expanduser(p.strip())
    return p if os.path.isabs(p) else os.path.normpath(os.path.join(task, p))


def set_ranking(task, path):
    """`--ranking PATH`: record its absolute path in meta.kernel_extraction.ranking_json before the steps run
    (meta.json is rewritten only when the value changes; a changed path is a changed test)."""
    meta_path = os.path.join(task, "meta.json")
    meta = _read_json(meta_path)
    if not isinstance(meta, dict):
        return False
    ke = meta.get("kernel_extraction")
    if not isinstance(ke, dict):
        ke = meta["kernel_extraction"] = {}
    path = os.path.abspath(os.path.expanduser(path))
    if ke.get("ranking_json") == path:
        return False
    ke["ranking_json"] = path
    _write_json(meta_path, meta)
    return True


def ranking_identities(task, meta):
    """(where, [identity]) of the first class that names this kernel's ranking row (A35 supplement 2):
    meta.kernel_extraction.ranking_row; else meta.device_kernel with the joint_ut phases' device kernels; else
    meta.kernel_extraction.selected_device_kernels (or selected_device_kernel), else run/requested_kernel.json's
    device_kernel. An identity is {"name": str} (matched against a row's device_kernel, name and id) or, for a
    ranking_row object, {"id": str, "name": str} (either one matches)."""
    ke = meta.get("kernel_extraction") if isinstance(meta.get("kernel_extraction"), dict) else {}
    rr = ke.get("ranking_row")
    if isinstance(rr, str) and rr.strip():
        return "meta.kernel_extraction.ranking_row", [{"name": rr}]
    if isinstance(rr, dict):
        ident = {k: rr[k] for k in ("id", "name") if isinstance(rr.get(k), str) and rr[k].strip()}
        if ident:                 # {rank, pct_gpu_time, share_of_phase_pct} alone does not name a row
            return "meta.kernel_extraction.ranking_row", [ident]
    names = _names(meta.get("device_kernel"))
    joint = meta.get("joint_ut") if isinstance(meta.get("joint_ut"), dict) else {}
    for ph in joint.get("phases") or []:
        if isinstance(ph, dict):
            names += _names(ph.get("device_kernel"))
    if names:
        return "meta.device_kernel" + (" / meta.joint_ut.phases[].device_kernel" if joint.get("phases") else ""), \
            [{"name": n} for n in dict.fromkeys(names)]
    names = _names(ke.get("selected_device_kernels")) or _names(ke.get("selected_device_kernel"))
    if names:
        return "meta.kernel_extraction.selected_device_kernels", [{"name": n} for n in dict.fromkeys(names)]
    req = _read_json(os.path.join(task, "run", "requested_kernel.json"))
    names = _names((req or {}).get("device_kernel")) if isinstance(req, dict) else []
    if names:
        return "run/requested_kernel.json device_kernel", [{"name": n} for n in dict.fromkeys(names)]
    return None, []


def _row_matches(row, ident):
    if not isinstance(row, dict):
        return False
    if "id" in ident and row.get("id") is not None and _ws(str(row.get("id"))) == _ws(ident["id"]):
        return True
    want = _ws(ident.get("name"))
    if want is None:
        return False
    if "id" not in ident and row.get("id") is not None and _ws(str(row.get("id"))) == want:
        return True
    return want in (_ws(row.get("device_kernel")), _ws(row.get("name")))


def ranking_phases(ranking, rows):
    """Lower-case phase names of a ranking: its `phases` and every phase a row counts."""
    out = set()
    ph = ranking.get("phases") if isinstance(ranking, dict) else None
    if isinstance(ph, dict):
        out |= {str(k).strip().lower() for k in ph}
    elif isinstance(ph, list):
        out |= {str(k).strip().lower() for k in ph if isinstance(k, str)}
    for r in rows:
        for fld in ("calls", "share_of_phase_pct"):
            if isinstance(r.get(fld), dict):
                out |= {str(k).strip().lower() for k in r[fld]}
    return out


def phase_names(value):
    """The phase names a meta.phase_regimes.<label>.phase gives (A35 second supplement): one name, a list of names,
    or names joined with "+" ("DECODE+PREFILL"); lower case, whitespace stripped, empty parts dropped."""
    names = []
    for v in (value if isinstance(value, list) else [value]):
        if isinstance(v, str):
            names += [s.strip().lower() for s in v.split("+")]
    return [s for s in dict.fromkeys(names) if s]


def label_phases(meta, label, phases):
    """The phases a regime label belongs to (A35 supplement, point 1), in this order: every phase
    meta.phase_regimes.<label>.phase names (any case; one name, a list, or names joined with "+": the second
    supplement); else the label itself when it is a phase name; else the phase whose name and "_" begin the label
    (prefill_graph, prefill_eager -> prefill; decode_lmhead -> decode). A .phase that names no phase
    ("DECODE (sibling branches)") places the label in no phase. Empty: no phase."""
    lab = str(label if label is not None else "").strip().lower()
    pr = meta.get("phase_regimes") if isinstance(meta.get("phase_regimes"), dict) else {}
    for k, v in pr.items():
        if str(k).strip().lower() == lab and isinstance(v, dict):
            names = phase_names(v.get("phase"))
            if names:
                return set(names)
    if lab in phases:
        return {lab}
    for ph in sorted(phases, key=len, reverse=True):
        if ph and lab.startswith(ph + "_"):
            return {ph}
    return set()


def _covers(meta, label, phase, phases):
    """Does a case or served label count for `phase`: the label is the phase, or belongs to it."""
    lab = str(label if label is not None else "").strip().lower()
    return lab == phase or phase in label_phases(meta, lab, phases)


def _uncovered_entries(wl, p):
    """meta.workload.uncovered as [(phase key, entry)]: a map phase -> {calls, why, ...} (a list of entries
    naming their `phase` is read too)."""
    unc = wl.get("uncovered")
    if unc is None:
        return []
    if isinstance(unc, dict):
        return list(unc.items())
    if isinstance(unc, list) and all(isinstance(e, dict) and isinstance(e.get("phase", e.get("regime")), str)
                                     for e in unc):
        return [(e.get("phase", e.get("regime")), e) for e in unc]
    p.add("meta.workload.uncovered must map each phase to {calls, why} (the calls of a covered phase this UT "
          f"does not time, with the reason; {PHASES_DOC})")
    return []


def check_measured_phases(task, meta, p):
    """A35: every phase this kernel has calls in -- in the extraction's kernel ranking (its row's calls or
    share_of_phase_pct above 0), in meta.workload.cases (effective_calls above 0) or in meta.workload.uncovered
    (calls above 0) -- is in served_regimes (when given) and has a timing case and a correctness case in
    case_manifest, counting every label that is the phase or belongs to it (label_phases). meta.workload.uncovered
    may only hold the remaining calls of such a covered phase; every entry has calls and why. Only for a task
    with meta.workload (an AgentX extraction); the ranking is required when meta.workload.kind is
    agentx_trace_replay."""
    wl = meta.get("workload")
    if not isinstance(wl, dict):
        return                                   # A19 normal mode: nothing observed to compare with
    path = ranking_path(task, meta)
    ranking, rows, row_note = None, [], ""
    if path is None:
        if wl.get("kind") == AGENTX_KIND:
            p.add(f"meta.workload.kind is {AGENTX_KIND} but no kernel ranking is given: run generate_ut.py with "
                  "--ranking <the extraction's kernel_ranking.json> (PREVIOUS_RANKING_JSON on an AgentX resume; it is "
                  "written into meta.kernel_extraction.ranking_json); the check compares the phases this kernel has "
                  f"calls in with the case manifest ({PHASES_DOC})")
    else:
        try:
            ranking = _read_json(path)
        except (OSError, ValueError) as exc:
            p.add(f"kernel ranking {path} (meta.kernel_extraction.ranking_json) cannot be read: "
                  f"{type(exc).__name__}: {exc}")
        else:
            if ranking is None:
                p.add(f"kernel ranking {path} (meta.kernel_extraction.ranking_json) does not exist")
            elif not isinstance(ranking, dict) or not isinstance(ranking.get("ranking"), list):
                p.add(f"kernel ranking {path} has no `ranking` list of kernel rows")
                ranking = None
    if ranking is not None:
        where, idents = ranking_identities(task, meta)
        if not idents:
            p.add(f"no kernel name to find this kernel's row of the ranking {path}: write meta.device_kernel, or name "
                  "the row with meta.kernel_extraction.ranking_row (its id or name)")
        for ident in idents:
            hit = [r for r in ranking["ranking"] if _row_matches(r, ident)]
            if not hit:
                shown = ident.get("name") or ident.get("id")
                p.add(f"the ranking {path} has no row whose device_kernel, name or id is {shown[:160]!r} (from "
                      f"{where}): name the row with meta.kernel_extraction.ranking_row (its id or name)")
            for r in hit:
                if r not in rows:
                    rows.append(r)
        row_note = "; ".join(f"row {r.get('rank', '?')} {str(r.get('name') or r.get('device_kernel') or r.get('id'))[:80]!r}"
                             for r in rows)
    entries = _uncovered_entries(wl, p)
    phases = ranking_phases(ranking, rows) | {"prefill", "decode"} | \
        {str(ph).strip().lower() for ph, _e in entries if str(ph).strip()}
    measured = {}
    for r in rows:
        for fld in ("calls", "share_of_phase_pct"):
            for ph, v in ((r.get(fld) or {}) if isinstance(r.get(fld), dict) else {}).items():
                if _positive(v):
                    measured.setdefault(str(ph).strip().lower(), []).append(f"ranking {fld}.{ph}={v}")
    by_label = {}
    for c in wl.get("cases") or []:
        if isinstance(c, dict) and _positive(c.get("effective_calls")):
            lab = str(c.get("regime") or "").strip().lower()
            by_label[lab] = by_label.get(lab, 0.0) + float(c["effective_calls"])
    for lab, n in by_label.items():
        measured.setdefault(lab, []).append(f"meta.workload.cases effective_calls={n:g}")
    for ph, e in entries:
        if not isinstance(e, dict) or "calls" not in e or not str(e.get("why") or "").strip():
            p.add(f"meta.workload.uncovered.{ph} needs calls and why ({PHASES_DOC})")
        if isinstance(e, dict) and _positive(e.get("calls")):
            measured.setdefault(str(ph).strip().lower(), []).append(f"meta.workload.uncovered.{ph} calls={e['calls']}")
    measured.pop("", None)
    served = [str(r).strip().lower() for r in (meta.get("served_regimes") or wl.get("served_regimes") or [])]
    man = meta.get("case_manifest") if isinstance(meta.get("case_manifest"), dict) else {}
    cases = [c for c in (man.get("cases") or []) if isinstance(c, dict)]
    covered = set()
    for ph in sorted(measured):
        roles = set()
        for c in cases:
            if _covers(meta, c.get("regime"), ph, phases) and isinstance(c.get("roles"), list):
                roles |= set(c["roles"])
        missing = []
        if served and not any(_covers(meta, s, ph, phases) for s in served):
            missing.append(f"served_regimes {served} has no label of it")
        for need in ("timing", "correctness"):
            if need not in roles:
                missing.append(f"case_manifest has no {need} case of it")
        if not missing:
            covered.add(ph)
            continue
        src = f" (ranking {path}: {row_note})" if rows else ""
        p.add(f"phase {ph}: this kernel has calls in it ({'; '.join(measured[ph])}){src}, but "
              + " and ".join(missing) + ". Every phase the kernel has calls in needs a timing case and a correctness "
              "case with that phase's deployed launch configuration, and a label in served_regimes when it is given. "
              "A label counts for the phase it belongs to: meta.phase_regimes.<label>.phase when given (write it to "
              "place a label in a phase; it may name several phases, as a list or joined with '+', e.g. "
              "\"DECODE+PREFILL\"), else the label itself when it is a phase name, else the phase whose name "
              "and '_' begin it (prefill_graph -> prefill). meta.workload.uncovered may only hold the remaining calls "
              f"of a covered phase ({PHASES_DOC})")
    for ph, e in entries:
        key = str(ph).strip().lower()
        if isinstance(e, dict) and _positive(e.get("calls")) and key not in covered:
            p.add(f"meta.workload.uncovered.{ph} declares {e.get('calls')} calls of a phase without its timing and "
                  "correctness cases: uncovered may only record the remaining calls of a covered phase; write the "
                  f"phase's cases instead ({PHASES_DOC})")


def scan_cross_rank(task):
    """[(file, line, symbol)] of cross-device symbols in kernel_src/ (the reverse check of a single-rank
    declaration). Comments are scanned too: a declared single-rank kernel must explain any hit."""
    hits = []
    root = os.path.join(task, "kernel_src")
    for dirpath, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d not in ("__pycache__", "build", ".geak_build")]
        for f in sorted(files):
            if not ut_runner.SOURCE_EXT.search(f):
                continue
            path = os.path.join(dirpath, f)
            try:
                with open(path, encoding="utf-8", errors="replace") as fh:
                    for i, line in enumerate(fh, 1):
                        for m in CROSS_RANK_RE.finditer(line):
                            hits.append((os.path.relpath(path, task), i, m.group(0)))
            except OSError:
                continue
    return hits


def check(task):
    p, warnings = Problems(), []
    meta = _read_json(os.path.join(task, "meta.json"))
    if meta is None or not isinstance(meta, dict):
        out = {"ok": False, "problems": ["meta.json missing" if meta is None else "meta.json must be a JSON object"],
               "warnings": []}
        _write_json(os.path.join(task, "run", "ut_check.json"), out)     # never leave an earlier pass standing
        return out
    world = 1
    try:
        world = check_meta(task, meta, p, warnings)
        check_manifest(meta, p)
        check_measured_phases(task, meta, p)
    except Exception as exc:          # ISSUE-014: a malformed meta is a named problem, never a crash
        p.add(f"meta.json could not be checked: {type(exc).__name__}: {exc}")
    try:
        with open(os.path.join(task, "cases.py"), encoding="utf-8") as fh:
            hooks = _hooks(fh.read())
    except FileNotFoundError:
        p.add("cases.py missing")
        hooks = {}
    except SyntaxError as exc:
        p.add(f"cases.py does not parse: {exc}")
        hooks = {}
    except Exception as exc:          # ISSUE-014
        p.add(f"cases.py could not be read: {type(exc).__name__}: {exc}")
        hooks = {}
    caps = meta.get("capabilities") or {}
    if not isinstance(caps, dict):    # check_meta named it; ISSUE-014: never a crash
        caps = {}
    if hooks:
        for need in ("call", "timing_cases", "random_shapes", "eager_cases"):
            if need not in hooks:
                p.add(f"cases.py lacks {need}")
        regimes = (meta.get("phase_regimes") or {}).values() if isinstance(meta.get("phase_regimes"), dict) \
            else [meta.get("regime") or {}]
        if any(_graph(r) for r in regimes if isinstance(r, dict)) and "replay" not in hooks:
            p.add("a phase deploys under a CUDA graph: cases.py must define replay(h, meta[, phase]) "
                  "(one group or a list of groups, each recording one graph: >=2 cases, inputs refreshed in "
                  "place, the deployment graphs it reproduces in `graphs`)")
        if caps.get("stateful") and "sequence_cases" not in hooks:
            p.add("capabilities.stateful: cases.py must define sequence_cases(h, meta) (ordered steps whose later "
                  "calls read the state earlier calls wrote, each naming its stateful tier)")
    req = _read_json(os.path.join(task, "run", "requested_kernel.json"))
    if req is not None:
        # A17.5: a GPU count written in the request equals world_size; with world_size > 1 the request or
        # the returned result must write it (the result is checked at delivery).
        declared = req.get("required_gpu_count")
        if declared is not None and declared != world:
            p.add(f"run/requested_kernel.json required_gpu_count={declared!r} differs from "
                  f"capabilities.multi_rank.world_size={world}")
        elif declared is None and world > 1:
            warnings.append(f"run/requested_kernel.json writes no required_gpu_count: RETURN.json must declare "
                            f"required_gpu_count={world} (world_size {world})")
    else:
        warnings.append("run/requested_kernel.json not found: the GPU-count declaration is checked at delivery")
    if world == 1:
        hits = scan_cross_rank(task)
        if hits and not str(caps.get("single_rank_justification") or "").strip():
            p.add("declared single-rank but kernel_src/ uses cross-device symbols "
                  f"({', '.join(f'{f}:{l} {s}' for f, l, s in hits[:8])}{' ...' if len(hits) > 8 else ''}); "
                  "declare capabilities.multi_rank, or write capabilities.single_rank_justification")
        elif hits:
            warnings.append(f"{len(hits)} cross-device symbol(s) in kernel_src/ accepted by "
                            f"single_rank_justification")
    out = {"ok": not p, "problems": list(p), "warnings": warnings, "world_size": world}
    _write_json(os.path.join(task, "run", "ut_check.json"), out)
    return out


# --------------------------------------------------------------------------- freeze
def freeze(task):
    meta = _read_json(os.path.join(task, "meta.json"))
    names = ut_runner.contract_file_list(task, meta)
    computed = ut_runner.compute_contract(task, names)
    origins = {}
    for rel, origin in ((meta.get("kernel_extraction") or {}).get("source_origins") or {}).items():
        if os.path.isfile(origin) and os.path.isfile(os.path.join(task, rel)):
            origins[rel] = {"origin": origin, "sha256": ut_runner.sha256_file(origin)}
    # A16 C': the declared binding files as frozen (not part of contract_sha256: kernel_src/ never is).
    bindings = {}
    for rel in (meta.get("kernel_extraction") or {}).get("binding_files") or []:
        if isinstance(rel, str) and os.path.isfile(os.path.join(task, rel)):
            bindings[os.path.normpath(rel)] = ut_runner.sha256_file(os.path.join(task, rel))
    world = ut_runner.world_size(meta)
    doc = {"contract": ut_runner.CONTRACT_NAME, "generated_by": VERSION,
           "frozen_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
           "files": computed["files"], "contract_sha256": computed["contract_sha256"],
           "world_size": world, "capabilities": meta.get("capabilities"),
           "timeouts": ut_runner.timeouts(meta, world), "kernel_src_origin": origins,
           "binding_files": bindings}
    _write_json(os.path.join(task, "run", "ut_contract.json"), doc)
    return {"ok": True, "contract_sha256": computed["contract_sha256"],
            "inputs": {f["path"]: f["sha256"] for f in computed["files"]},
            "outputs": _digests(task, ["run/ut_contract.json"])}


# --------------------------------------------------------------------------- step bookkeeping
def _step_inputs(task, step):
    meta = _read_json(os.path.join(task, "meta.json"))
    meta = meta if isinstance(meta, dict) else {}      # not an object: check() names it, the record must not crash
    if step == "check":
        names = ["meta.json", "cases.py", "unittest.py", "run/requested_kernel.json", *ut_runner.RUNTIME_FILES]
        return dict(_digests(task, names), **{"<kernel_src>": _kernel_src_digest(task),
                                              "<ranking>": _ranking_digest(task, meta)})
    if step == "freeze":
        try:
            return _digests(task, ut_runner.contract_file_list(task, meta))
        except Exception:
            return {"<unlisted>": None}
    return {f"<shared>/{n}": ut_runner.sha256_file(os.path.join(_HERE, n)) for n in ut_runner.RUNTIME_FILES}


def _kernel_src_digest(task):
    """One digest of the kernel_src/ source files (names and contents): the check classifies them (A16 C'),
    so a file added, removed or changed there reruns the check."""
    files = [[rel, _digest(task, rel)] for rel in kernel_src_sources(task)]
    return hashlib.sha256(json.dumps(files).encode()).hexdigest()


def _ranking_digest(task, meta):
    """sha256 of the kernel ranking meta.kernel_extraction.ranking_json names (A35): a changed ranking reruns the
    check. None without a ranking."""
    path = ranking_path(task, meta or {})
    return ut_runner.sha256_file(path) if path and os.path.isfile(path) else None


def _current(task, rec):
    """Does a recorded step still match the disk?"""
    if not rec or not rec.get("ok"):
        return False
    for name, sha in (rec.get("inputs") or {}).items():
        if name == "<kernel_src>":
            if _kernel_src_digest(task) != sha:
                return False
        elif name == "<ranking>":
            if _ranking_digest(task, _read_json(os.path.join(task, "meta.json")) or {}) != sha:
                return False
        elif name.startswith("<shared>/"):
            if ut_runner.sha256_file(os.path.join(_HERE, name.split("/", 1)[1])) != sha:
                return False
        elif _digest(task, name) != sha:
            return False
    for name, sha in (rec.get("outputs") or {}).items():
        if _digest(task, name) != sha:
            return False
    return True


def run_step(task, step, force=False):
    if step == "vendor":
        rec = vendor(task, force=force)
    elif step == "check":
        res = check(task)
        rec = dict(res, inputs=_step_inputs(task, "check"), outputs=_digests(task, ["run/ut_check.json"]))
    else:
        rec = freeze(task)
    rec["at"] = time.strftime("%Y-%m-%dT%H:%M:%S%z")
    return rec


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("step", choices=("all",) + STEPS)
    ap.add_argument("task")
    ap.add_argument("--force", action="store_true", help="vendor over a hand-written unittest.py")
    ap.add_argument("--ranking", default="", metavar="KERNEL_RANKING_JSON",
                    help="the kernel ranking of the extraction (A35): its absolute path is written into "
                         "meta.kernel_extraction.ranking_json before the steps run (give it on the first `all`, "
                         "before freeze: a changed path is a changed meta.json)")
    a = ap.parse_args(argv)
    task = os.path.realpath(a.task)
    if a.ranking:
        set_ranking(task, a.ranking)
    state_path = os.path.join(task, STATE)
    state = _read_json(state_path, {}) or {}
    steps = state.setdefault("steps", {})
    order = STEPS if a.step == "all" else (a.step,)
    redo = a.step != "all"
    report = {"task": task, "ran": [], "kept": []}
    for step in order:
        if not redo and _current(task, steps.get(step)):
            report["kept"].append(step)
            continue
        redo = True                       # this step reruns -> every later step reruns too
        rec = run_step(task, step, force=a.force)
        steps[step] = rec
        report["ran"].append(step)
        if not rec.get("ok"):
            for later in STEPS[STEPS.index(step) + 1:]:
                steps.pop(later, None)
            _write_json(state_path, state)
            report.update(ok=False, failed=step, problems=rec.get("problems"), warnings=rec.get("warnings"))
            print(json.dumps(report, indent=1, ensure_ascii=False))
            return 1
    if a.step != "all":
        for later in STEPS[STEPS.index(a.step) + 1:]:
            steps.pop(later, None)        # a later step must be run again after this one
    _write_json(state_path, state)
    ck = steps.get("check") or {}
    report.update(ok=True, warnings=ck.get("warnings") or [],
                  contract_sha256=(steps.get("freeze") or {}).get("contract_sha256"))
    print(json.dumps(report, indent=1, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
