def _hooks(cases_src):
    """Top-level callables / names defined by cases.py (AST only, never imported)."""
    tree = ast.parse(cases_src)
    names = {}
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            pos = [a for a in node.args.posonlyargs + node.args.args]
            names[node.name] = {"kind": "def", "positional": len(pos),
                                "required": len(pos) - len(node.args.defaults)}
        elif isinstance(node, ast.ClassDef):
            names[node.name] = {"kind": "class"}
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            for t in targets:
                if isinstance(t, ast.Name):
                    names[t.id] = {"kind": "assign"}
        elif isinstance(node, (ast.Import, ast.ImportFrom)):
            for a in node.names:
                names[(a.asname or a.name).split(".")[0]] = {"kind": "import"}
    return names


def _graph(regime):
    regime = regime or {}
    if regime.get("enforce_eager"):
        return False
    return bool(regime.get("cuda_graph", True))


def _finite_number(x, positive=False, allow_zero=True):
    if isinstance(x, bool) or not isinstance(x, (int, float)) or not math.isfinite(x):
        return False
    return x > 0 if positive else (x >= 0 if allow_zero else x > 0)


def check_meta(task, meta, p, warnings):
    tc = meta.get("target_callable")
    if not isinstance(tc, str) or not re.match(r"^[\w.]+:[\w.]+$", tc or ""):
        p.add("meta.target_callable must be an exact 'module:attr' spec")
    b = meta.get("candidate_bind") or {}
    if b.get("kind") == "rebind":
        for k in ("target", "impl_module", "impl_attr", "file"):
            if not b.get(k):
                p.add(f"meta.candidate_bind (rebind) lacks {k}")
    elif b.get("kind") == "module" or b.get("module"):
        for k in ("module", "file"):
            if not b.get(k):
                p.add(f"meta.candidate_bind (module) lacks {k}")
    else:
        p.add("meta.candidate_bind must be {kind: module, module, file} or {kind: rebind, target, impl_module, impl_attr, file}")
    if b.get("file") and not str(b["file"]).startswith("kernel_src/"):
        p.add("meta.candidate_bind.file must live under kernel_src/")
    elif b.get("file") and not os.path.isfile(os.path.join(task, b["file"])):
        p.add(f"meta.candidate_bind.file {b['file']} does not exist")
    try:
        tol = ut_runner._load  # noqa: F841 (keep import side effects explicit)
        t = (meta.get("tolerance") or {}).get("tol") if isinstance(meta.get("tolerance"), dict) else meta.get("tol")
        if not _finite_number(t):
            p.add("meta.tolerance.tol must be a finite non-negative number")
    except Exception as exc:
        p.add(f"meta.tolerance: {exc}")
    for prob in harness_lib.per_output_tolerances(meta)[1]:      # A42: per-output tolerances, well formed
        p.add(prob)
    pr = meta.get("phase_regimes")
    if pr is not None and (not isinstance(pr, dict) or not pr or
                           not all(isinstance(v, dict) for v in pr.values())):
        p.add("meta.phase_regimes must map every phase label to a regime object")
    if pr is None and not isinstance(meta.get("regime"), dict):
        p.add("meta.regime (or meta.phase_regimes) is required: the deployed graph/compile settings")
    wl = meta.get("workload")
    if wl is not None and (not isinstance(wl, dict) or not isinstance(wl.get("cases"), list) or not wl["cases"]):
        # A19: optional; without it the UT times the cases unweighted (main's normal mode)
        p.add("meta.workload, when given, needs cases (observed case model with sig, regime, effective_calls)")
    elif wl is None:
        warnings.append("meta.workload absent: the UT times every timing case unweighted (primary metric: the "
                        "unweighted geomean); an AgentX extraction must record the observed workload")
    caps = meta.get("capabilities")
    if not isinstance(caps, dict):
        p.add("meta.capabilities is required: {stateful, multi_rank: {world_size, ...}}")
        caps = {}
    if not isinstance(caps.get("stateful"), bool):
        p.add("meta.capabilities.stateful must be true or false")
    elif caps.get("stateful"):
        for prob in harness_lib.stateful_tier_problems(meta):        # A18.4
            p.add(prob)
    mr = caps.get("multi_rank")
    if not isinstance(mr, dict) or not isinstance(mr.get("world_size"), int) or isinstance(mr.get("world_size"), bool) \
            or mr.get("world_size", 0) < 1:
        p.add("meta.capabilities.multi_rank.world_size must be a positive integer (1 for a single-GPU kernel)")
        mr = {"world_size": 1}
    world = mr.get("world_size", 1)
    if world > 1:
        if not MULTI_RANK_SUPPORTED:
            p.add("world_size > 1: multi-rank execution is not available in this GEAK version; keep this kernel "
                  "on the legacy path (collective-ut.md)")
        if mr.get("comm") not in ("collective_api", "peer_memory"):
            p.add("capabilities.multi_rank.comm must be 'collective_api' or 'peer_memory'")
        inputs = mr.get("inputs")
        if not isinstance(inputs, dict) or not inputs or \
                any(v not in ("replicated", "per_rank") for v in inputs.values()):
            p.add("capabilities.multi_rank.inputs must map every input to 'replicated' or 'per_rank'")
        ev = mr.get("evidence")
        if not isinstance(ev, dict) or not any(ev.get(k) for k in ev):
            p.add("capabilities.multi_rank.evidence must say why this kernel is multi-rank (serving TP, "
                  "per-rank launches in the trace, IPC / peer-memory / collective symbols in the source)")
    plugin = harness_lib.compare_plugin_problem(meta)       # A42: refused, never accepted, frozen and left unused
    if plugin:
        p.add(plugin)
    tm = meta.get("timeouts")
    if tm is not None:
        if not isinstance(tm, dict) or any(k not in ("setup_s", "command_s", "total_s") for k in tm):
            p.add("meta.timeouts may only hold setup_s, command_s, total_s")
        else:
            for k, v in tm.items():
                if not _finite_number(v):
                    p.add(f"meta.timeouts.{k} must be a non-negative number of seconds")
            if tm.get("total_s") and tm.get("command_s") and tm["command_s"] > tm["total_s"]:
                p.add("meta.timeouts.command_s exceeds total_s")
    elif world > 1:
        warnings.append("meta.timeouts absent: multi-rank defaults setup_s=900, command_s=1800, total_s=3600 apply")
    ctl = meta.get("controls") or {}
    for name, why in (ctl.get("disabled") or {}).items():
        if not isinstance(why, str) or len(why.strip()) < 10:
            p.add(f"meta.controls.disabled.{name} needs a written reason")
    for c in ctl.get("task") or []:
        if not isinstance(c, dict) or not c.get("name") or not c.get("file") or \
                not os.path.isfile(os.path.join(task, c.get("file", ""))):
            p.add(f"meta.controls.task entry {c!r} needs name and an existing file")
        elif c.get("expect", "reject") not in ("reject", "below_tol"):
            p.add(f"task control {c['name']}: expect must be 'reject' or 'below_tol'")
    gaps = (meta.get("coverage") or {}).get("gaps") if isinstance(meta.get("coverage"), dict) else None
    if gaps:
        p.add(f"meta.coverage.gaps is not empty (ISSUE-012: declared coverage gaps block delivery): {gaps}")
    check_kernel_src_classes(task, meta, p)
    tmeta = meta.get("timing")
    if isinstance(tmeta, dict):
        for key in EAGER_SPIN_KEYS:
            v = tmeta.get(key)
            if v is not None and (isinstance(v, bool) or not isinstance(v, (int, float)) or not v > 0
                                  or not math.isfinite(v)):
                p.add(f"meta.timing.{key} must be a positive number (A16 eager spin setting), got {v!r}")
        v = tmeta.get("graph_inner_max_factor")
        if v is not None and (isinstance(v, bool) or not isinstance(v, int) or v < 1):
            p.add(f"meta.timing.graph_inner_max_factor must be a positive integer (A20: how far the UT may raise "
                  f"a host-dominated graph case's inner), got {v!r}")
    check_graph_capture(meta, p)
    return world


def check_graph_capture(meta, p):
    """A18.2: every graph-deployed phase declares the deployment's graph capture (captured sizes, padding
    rule) and every timing case with call mass in it has an `m` and every other case_manifest dimension, so
    the UT can name the deployment graph each case replays in (M padded, the other dimensions as in the case)."""
    try:
        graphs = harness_lib.deployment_graphs(meta)
    except Exception as exc:          # ISSUE-014: a malformed meta is a named problem
        p.add(f"graph capture declaration could not be checked: {type(exc).__name__}: {exc}")
        return
    for phase, info in graphs.items():
        for prob in info.get("problems") or []:
            p.add(prob)


