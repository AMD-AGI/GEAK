def is_generated(task):
    try:
        with open(os.path.join(task, "unittest.py"), encoding="utf-8") as fh:
            return fh.readline().startswith(ut_runner.GENERATED_MARKER)
    except OSError:
        return False


def vendor(task, force=False):
    meta_path = os.path.join(task, "meta.json")
    if not os.path.isfile(meta_path):
        raise SystemExit("vendor: write meta.json first (task-authoring.md)")
    ut = os.path.join(task, "unittest.py")
    if os.path.isfile(ut) and not is_generated(task):
        if not force:
            raise SystemExit("vendor: unittest.py is hand-written (no generated marker); move it away or pass "
                             "--force (it is then kept as run/unittest.handwritten.py)")
        os.makedirs(os.path.join(task, "run"), exist_ok=True)
        shutil.copy2(ut, os.path.join(task, "run", "unittest.handwritten.py"))
    for name in ut_runner.RUNTIME_FILES:
        shutil.copy2(os.path.join(_HERE, name), os.path.join(task, name))
    with open(ut, "w", encoding="utf-8") as fh:
        fh.write(UNITTEST_TEMPLATE)
    overlay = os.path.join(task, "baseline_overlay")
    if not os.path.isfile(os.path.join(overlay, "_overlay_manifest.json")):
        sys.path.insert(0, _HERE)
        import overlay_setup  # noqa: E402
        overlay_setup._ensure_overlay(overlay)
    meta = _read_json(meta_path)
    ke = meta.setdefault("kernel_extraction", {})
    files = list(ke.get("source_delivery_files") or [])
    for name in ut_runner.RUNTIME_FILES:
        if name not in files:
            files.append(name)
    if ke.get("source_delivery_files") != files:
        ke["source_delivery_files"] = files
        _write_json(meta_path, meta)
    inputs = {f"<shared>/{n}": ut_runner.sha256_file(os.path.join(_HERE, n)) for n in ut_runner.RUNTIME_FILES}
    outputs = _digests(task, [*ut_runner.RUNTIME_FILES, "unittest.py", "meta.json",
                              "baseline_overlay/sitecustomize.py", "baseline_overlay/_overlay_manifest.json"])
    return {"ok": True, "inputs": inputs, "outputs": outputs}


