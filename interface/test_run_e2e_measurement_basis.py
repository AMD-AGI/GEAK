    assert out["final_throughput_tok_s"] == 1100.0
    assert out["baseline_throughput_tok_s"] == 1000.0
    assert out["final_overlay"] == str(cand_dir)
    assert out["validation_evidence"]["validate_final_missing"] is True
    _assert_self_consistent(out)


