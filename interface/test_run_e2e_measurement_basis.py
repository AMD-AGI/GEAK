def test_the_cold_ratio_pairs_legs_from_the_same_session(tmp_path: Path) -> None:
    """The Setup cold round ran on a genuinely cold box and the Validate one did
    not, so pairing across them manufactures a gain that the same-session pair
    does not show."""
    eval_dir = _eval_dir(
        tmp_path, setup_base=1000.0, setup_cold=700.0,
        base_leg=1000.0, base_leg_cold=900.0,
        final_leg=1010.0, final_cold=910.0,
    )
    out = rx.normalize_result({}, _wf(eval_dir, base=1000.0, final=1010.0, speedup=1.01))
    am = out["alignment_metrics"]

    assert am["cold_pairing"] == "same_session"
    assert am["cold_geak_speedup"] == rx._safe_ratio(910.0, 900.0)   # not 910/700
    assert am["cold_penalty_pct_baseline"] == -10.0
    assert am["cold_penalty_pct_final"] == round((910.0 - 1010.0) / 1010.0 * 100, 3)
    assert out["final_throughput_basis"] == "hot"


