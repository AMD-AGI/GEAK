def test_the_kernels_each_leg_actually_selected_are_recorded(
    tmp_path: Path, monkeypatch
) -> None:
    """Two servers can take the same flags and come up on different kernels.
    result.json has to say which ones, or the only record is a server log."""
    eval_dir = _eval_dir(tmp_path, setup_base=1000.0, base_leg=1000.0, final_leg=1100.0)
    _write(eval_dir / "baseline" / "server.log", FALLBACK_SERVER_LOG)
    _write(eval_dir / "validation" / "base" / "server.log", ACCELERATED_SERVER_LOG)
    _with_launcher(monkeypatch, "native")

    stack = rx.normalize_result(
        {}, _wf(eval_dir, base=1000.0, final=1100.0, speedup=1.1)
    )["serving_stack"]

    assert stack["baseline"]["aiter_mentions"] == 1  # only the potential-backends list
    assert any("Triton" in pick for pick in stack["baseline"]["kernel_picks"])
    assert stack["validation_base"]["aiter_mentions"] == 6
    assert any("Aiter" in pick for pick in stack["validation_base"]["kernel_picks"])
    # The pid / module prefix is stripped so the pick reads as the pick.
    assert stack["baseline"]["kernel_picks"][0].startswith("Final IR op priority")


