def test_the_report_flags_an_unaligned_recipe_for_a_human(tmp_path: Path, monkeypatch) -> None:
    eval_dir = _eval_dir(tmp_path, setup_base=1000.0, base_leg=1000.0, final_leg=1100.0)
    _with_launcher(monkeypatch, "native")
    unaligned = rx.normalize_result(
        {"orchestrator_best_tput_same_config": 1130.0},
        _wf(eval_dir, base=1000.0, final=1100.0, speedup=1.1),
    )
    _with_launcher(monkeypatch, "magpie", "/ix/benchmarks/vllm_mi355x.sh")
    aligned = rx.normalize_result(
        {"orchestrator_best_tput_same_config": 1130.0},
        _wf(eval_dir, base=1000.0, final=1100.0, speedup=1.1),
    )

    unaligned_section = rx._render_baseline_alignment_section(unaligned)
    aligned_section = rx._render_baseline_alignment_section(aligned)

    assert "Server launch recipe: `native`" in unaligned_section
    assert "did not serve the same stack" in unaligned_section
    assert "Server launch recipe: `magpie`" in aligned_section
    assert "did not serve the same stack" not in aligned_section
    assert unaligned_section.count(rx.BASELINE_ALIGNMENT_BEGIN) == 1
