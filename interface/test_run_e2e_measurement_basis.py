    eval_dir = _eval_dir(
        tmp_path, setup_base=1000.0, base_leg=1000.0, final_leg=1005.0,
        validation={"validation_status": "validated_no_win", "noise_band_pct": 2.0},
    )
    ev = rx.normalize_result(
        {}, _wf(eval_dir, base=1000.0, final=1005.0, speedup=1.005)
    )["validation_evidence"]

    assert ev["validation_status"] == "validated_no_win"
    assert ev["delta_pct"] == 0.5
    assert ev["noise_band_pct"] == 2.0
    assert ev["significance_threshold_pct"] == 2.0
    assert ev["delta_exceeds_noise"] is False
    # The two criteria answer different questions and are allowed to disagree:
    # these benches repeat tightly enough to separate 0.5%, but the Director
    # declared a 2% band for the box, and the wider of the two governs.
    assert ev["spreads_non_overlapping"] is True


