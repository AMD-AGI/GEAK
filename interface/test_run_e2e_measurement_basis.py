def test_the_re_measured_base_leg_outranks_the_setup_baseline(tmp_path: Path) -> None:
    """The box drifted 5% between Setup and Validate. Only the leg measured
    next to the final can serve as the denominator."""
    eval_dir = _eval_dir(tmp_path, setup_base=1000.0, base_leg=950.0, final_leg=1000.0)
    out = rx.normalize_result({}, _wf(eval_dir, base=1000.0, final=1000.0, speedup=1.0))

    assert out["baseline_throughput_tok_s"] == 950.0
    basis = out["baseline_basis"]
    assert basis["baseline_basis_source"] == "validation_base_bench_summary"
    assert basis["setup_baseline_tok_s"] == 1000.0
    assert basis["baseline_drift_pct"] == -5.0
    _assert_self_consistent(out)


