#!/usr/bin/env python3
"""The measurement-basis contract of ``run_e2e.normalize_result``.

One invariant sits above every other rule here: a reader who divides the
``final_throughput_tok_s`` we publish by the ``baseline_throughput_tok_s`` we
publish must land on the ``throughput_speedup`` we publish. Every test below
protects one of the ways that used to break — a denominator measured hours
before the numerator, a basis switch that moved one side of the ratio, a cold
round compared against a differently-cold one, an arbitration verdict silently
replaced by the intermediate result it was convened to re-check, or a path
advertised for an artifact that was never produced.

Run: python3 -m pytest GEAK/interface/test_run_e2e_measurement_basis.py -v
"""
from __future__ import annotations

import importlib.util
import json
import re
from pathlib import Path

import pytest

_HERE = Path(__file__).resolve().parent


def _load():
    spec = importlib.util.spec_from_file_location("run_e2e", _HERE / "run_e2e.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


rx = _load()


@pytest.fixture(autouse=True)
def _no_inherited_axis(monkeypatch):
    """An exported E2E_METRIC selects the AgentX axis, and so the rule GEAK holds it to."""
    monkeypatch.delenv("E2E_METRIC", raising=False)

PATCH_WITH_HUNK = (
    "Provenance: generated by the e2e workflow\n"
    "--- a/mod.py\n+++ b/mod.py\n@@ -1 +1 @@\n-old\n+new\n"
)
PATCH_WITHOUT_HUNK = "Provenance: generated by the e2e workflow\nNo changes to apply.\n"


def _write(path: Path, payload) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(payload, str):
        path.write_text(payload, encoding="utf-8")
    else:
        path.write_text(json.dumps(payload), encoding="utf-8")
    return path


def _eval_dir(
    tmp_path: Path,
    *,
    setup_base: float = 1000.0,
    base_leg: float | None = None,
    final_leg: float | None = None,
    setup_cold: float | None = None,
    base_leg_cold: float | None = None,
    final_cold: float | None = None,
    validation: dict | None = None,
) -> Path:
    eval_dir = tmp_path / "e2e_cycle0"
    setup = {"throughput_tok_s_median": setup_base,
             "output_throughput_tok_s_spread_pct": 0.5}
    if setup_cold is not None:
        setup["cold_output_throughput_tok_s"] = setup_cold
    _write(eval_dir / "baseline" / "bench_summary.json", setup)
    if base_leg is not None:
        leg = {"throughput_tok_s_median": base_leg,
               "output_throughput_tok_s_spread_pct": 0.2}
        if base_leg_cold is not None:
            leg["cold_output_throughput_tok_s"] = base_leg_cold
        _write(eval_dir / "validation" / "base" / "bench_summary.json", leg)
    if final_leg is not None:
        leg = {"throughput_tok_s_median": final_leg,
               "output_throughput_tok_s_spread_pct": 0.3}
        if final_cold is not None:
            leg["cold_output_throughput_tok_s"] = final_cold
        _write(eval_dir / "validation" / "final" / "bench_summary.json", leg)
    if validation is not None:
        _write(eval_dir / "director_e2e_validation.json", validation)
    return eval_dir


def _wf(eval_dir: Path, *, base: float, final: float, speedup: float, **extra) -> dict:
    wf = {
        "eval_dir": str(eval_dir),
        "baseline_throughput_tok_s": base,
        "final_throughput_tok_s": final,
        "throughput_speedup": speedup,
        "output_parity": "pass",
    }
    wf.update(extra)
    return wf


def test_kb_return_retains_the_normalized_keep_verdict_and_pair(tmp_path):
    eval_dir = _eval_dir(tmp_path, setup_base=90, base_leg=100, final_leg=102)
    for leg in ("base", "final"):
        path = eval_dir / "validation" / leg / "bench_summary.json"
        summary = json.loads(path.read_text())
        summary.update(metric_basis="e2e_norm_intvty_p50",
                       guard_e2e_norm_intvty_p90_median=80,
                       guard_aggregate_output_tok_s_median=440)
        _write(path, summary)
    h = {"workload_spec": {"kind": "agentx_trace_replay", "acceptance": {
        "objective": "e2e_norm_intvty_p50", "min_gain_pct": 3,
        "guard_max_drop_pct": {"e2e_norm_intvty_p90": 5, "aggregate_output_tok_s": 5}}}}
    wf = _wf(eval_dir, base=90, final=102, speedup=102/90, validation_status="validated_win")
    normalized = rx.normalize_result(h, wf)
    stored = rx._enrich_kb_return(wf, normalized)
    assert stored["validation_evidence"]["acceptance"]["keep"] is False
    assert stored["baseline_throughput_tok_s"] == 100
    assert stored["throughput_speedup"] == 1.02


def _accepted_candidate(
    eval_dir: Path,
    name: str = "cand_fast_norm",
    *,
    ref: float = 1000.0,
    cand: float = 1100.0,
    delta: float = 10.0,
) -> Path:
    """An accepted intermediate A/B with a real, loadable overlay on disk."""
    cand_dir = eval_dir / "overlay" / name
    _write(cand_dir / "_overlay_manifest.json", {"modules": ["fast_norm"]})
    _write(cand_dir / "sitecustomize.py", "# overlay entry point\n")
    _write(cand_dir / "integrate_result.json", {
        "gate": "accepted",
        "short_name": name.removeprefix("cand_"),
        "e2e_delta_pct": delta,
        "ref_med": ref,
        "cand_med": cand,
        "e2e_throughput_tok_s": cand,
        "accepted_overlay": str(cand_dir),
        "output_parity": "pass",
    })
    return cand_dir


def _assert_self_consistent(out: dict) -> None:
    base = out["baseline_throughput_tok_s"]
    final = out["final_throughput_tok_s"]
    assert base > 0 and final > 0
    assert abs(final / base - out["throughput_speedup"]) <= rx.SPEEDUP_SELF_CONSISTENCY_TOL


